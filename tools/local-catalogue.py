#!/usr/bin/env python3
"""生成随仓库分发的目录表 `catalogue/skins.json`（skinId → stem / charId / name / group）。

**只含元数据**：skinId、stem、charId、名字、分组。没有美术文件、没有素材路径、没有 URL——可以安全地进 git。

这份表是插件构建的**第一优先名字来源**（`tools/skin-catalogue.py --local-catalogue`），所以做得成:

  * 本机提取产物（`data/skins-local.json`）里的名字是**残缺**的：提取器解不出官方显示名的那 99 套写成
    `name = skinId`、`group = ''`（本机实测 273 套里 174 套有真名）。缺的那些在这里用主项目由官方 gamedata
    生成的表补齐，于是本表 273/273 都有名字——**别的机器没有官方 gamedata 缓存也能拿到真名**。
  * stem 与 skinId 分别来自提取产物的目录名（`tools/assets/local-skin-index.json` 的 `byStem`）与
    提取元数据（`data/skins-local.json` 的 `spine.*.skel` 文件名），两条线**逐条互相核对**，不一致就报错退出。

来源（默认值针对主项目检出；都不写盘）：

  1. `--skin-index`   `tools/assets/local-skin-index.json`（分支 `feat/skins`，git 里的那份）
                      → `byStem`: stem → skinId（本机实测 273 条 / 174 个干员）。
  2. `--skins-meta`   `data/skins-local.json`（**未跟踪**的提取产物：由 `feat/skins` 分支的 `.gitignore` 挡住它）
                      → `chars[charId].skins[skinId]` 的 `name` / `group`（真名）与 `spine.*.skel`（反推 stem）。
  3. `--official-names` `data/skins.json`（分支 `feat/skins`，由官方 gamedata 生成）
                      → 名字/分组的补齐来源；`skinId` 不在里面就报错。
  4. `--official-table` `.cache/gamedata/excel/skin_table.json`（官方 gamedata 快照，**可选**）
                      → 只用来核对：`displaySkin.skinName` / `skinGroupName` 必须与第 3 项逐条一致。

用法：

    python tools/local-catalogue.py --out catalogue/skins.json \
        --repo <主项目检出> --ref feat/skins

`--skins-meta` / `--skin-index` / `--official-names` 给了就是磁盘文件，覆盖默认。**本脚本不联网。**
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

sys.stdout.reconfigure(encoding='utf-8')

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(REPO, 'catalogue', 'skins.json')
DEFAULT_MAINS = (r'D:\project\html\Stronghold-Protocol', r'E:\Stronghold-Protocol')
DEFAULT_REF = 'feat/skins'
SKIN_INDEX_PATH = 'tools/assets/local-skin-index.json'
SKINS_JSON_PATH = 'data/skins.json'
SKINS_META_PATH = 'data/skins-local.json'
OFFICIAL_TABLE_PATH = os.path.join('.cache', 'gamedata', 'excel', 'skin_table.json')

# 写进目录表的说明（不含任何 URL、不含任何素材路径）。
NOTE = ('Operator skin catalogue for the skin-models plugin build: skinId -> stem / charId / display name / skin '
        'group. Metadata only — no game art, no asset paths, no URLs. Generated by tools/local-catalogue.py from the '
        'Stronghold-Protocol checkout (branch feat/skins): tools/assets/local-skin-index.json (stem -> skinId) + '
        'data/skins-local.json (unpacked-client extraction metadata, untracked) + data/skins.json (the skin list the '
        'main project generates from the official gamedata). Names the extraction could not resolve are filled in '
        'from that generated list, so every entry here carries a real display name.')


def say(text=''):
    print(text, flush=True)


def sha256(raw):
    return hashlib.sha256(raw).hexdigest()


def git_bytes(repo, ref, path):
    """`git show <ref>:<path>` 的原始字节；文件不在这个 ref 上就返回 None。"""
    r = subprocess.run(['git', '-C', repo, 'show', f'{ref}:{path}'], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return r.stdout if r.returncode == 0 else None


def git_blob_id(repo, ref, path):
    r = subprocess.run(['git', '-C', repo, 'rev-parse', f'{ref}:{path}'], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return r.stdout.decode('ascii').strip() if r.returncode == 0 else None


def read_bytes(path):
    with open(path, 'rb') as fh:
        return fh.read()


def parse_json(raw, what):
    try:
        return json.loads(raw.decode('utf-8'))
    except (ValueError, UnicodeDecodeError) as err:
        raise SystemExit(f'{what}: 不是合法的 UTF-8 JSON（{err}）')


def first_dir(candidates):
    for path in candidates:
        if path and os.path.isdir(path):
            return os.path.abspath(path)
    return None


class Source:
    """一个输入文件的出处：磁盘路径或 git 里的 blob，附 sha256 / 字节数。

    `label` 是写进目录表的路径写法：磁盘文件写成主项目里的相对路径，免得那份随仓库分发的表里留下
    某台机器的绝对路径。
    """

    def __init__(self, role, path, ref=None, blob=None, raw=None, label=None):
        self.role = role
        self.path = path
        self.ref = ref
        self.blob = blob
        self.raw = raw
        self.label = label or path

    @property
    def from_text(self):
        return f'git {self.ref}:{self.path}' if self.ref else 'disk'

    def record(self):
        out = {'path': self.label.replace(os.sep, '/'), 'from': self.from_text,
               'sha256': sha256(self.raw), 'bytes': len(self.raw), 'role': self.role}
        if self.blob:
            out['blob'] = self.blob
        return out


def load_source(role, explicit, repo, ref, path, disk_default=None, hint='', label=None):
    """一个来源：显式路径 > `git <ref>:<path>` > 指定的磁盘兜底路径。

    `data/skins-local.json` 是**未跟踪**的提取产物，只可能从磁盘读，所以调用时直接把磁盘路径当显式值传进来。
    """
    if explicit:
        if not os.path.isfile(explicit):
            raise SystemExit(f'--{role} {explicit}: 不是一个文件{hint}')
        raw = read_bytes(explicit)
        return Source(role, os.path.abspath(explicit), raw=raw, label=label), parse_json(raw, explicit)
    if repo:
        raw = git_bytes(repo, ref, path)
        if raw is not None:
            return Source(role, path, ref=ref, blob=git_blob_id(repo, ref, path), raw=raw), parse_json(raw, f'{ref}:{path}')
    disk = disk_default or os.path.join(repo or '', path)
    if os.path.isfile(disk):
        raw = read_bytes(disk)
        return Source(role, disk, raw=raw, label=label), parse_json(raw, disk)
    raise SystemExit(f'读不到 {path}：给了 --repo 就在分支 {ref} 上找它，找不到再看磁盘 {disk}；'
                     f'也可以直接给 --{role} <文件>{hint}')


def main(argv):
    ap = argparse.ArgumentParser(description='生成随仓库分发的目录表 catalogue/skins.json（只含元数据）')
    ap.add_argument('--out', default=DEFAULT_OUT, help=f'输出文件（默认 {DEFAULT_OUT}）')
    ap.add_argument('--repo', help='主项目检出（默认探测 %s）' % '；'.join(DEFAULT_MAINS))
    ap.add_argument('--ref', default=DEFAULT_REF, help=f'主项目分支/提交（默认 {DEFAULT_REF}）')
    ap.add_argument('--skin-index', help=f'磁盘上的 {SKIN_INDEX_PATH}')
    ap.add_argument('--skins-meta', help=f'磁盘上的 {SKINS_META_PATH}（未跟踪的提取产物）')
    ap.add_argument('--official-names', help=f'磁盘上的 {SKINS_JSON_PATH}')
    ap.add_argument('--official-table', help=f'官方 gamedata 快照（可选，只用来核对）：{OFFICIAL_TABLE_PATH}')
    args = ap.parse_args(argv)

    repo = first_dir([args.repo] if args.repo else list(DEFAULT_MAINS))
    if args.repo and not repo:
        raise SystemExit(f'--repo {args.repo} 不是一个目录')
    if not repo and not (args.skin_index and args.skins_meta and args.official_names):
        raise SystemExit('找不到主项目检出：给 --repo <检出>，或把三个来源都用磁盘路径给全')

    index_src, index = load_source('skin-index', args.skin_index, repo, args.ref, SKIN_INDEX_PATH)
    names_src, names = load_source('official-names', args.official_names, repo, args.ref, SKINS_JSON_PATH)
    # 提取产物在主项目里是**未跟踪**的（由 feat/skins 分支的 .gitignore 挡住 data/skins-local.json），只从磁盘读。
    meta_src, meta = load_source('skins-meta', args.skins_meta, None, args.ref, SKINS_META_PATH,
                                 disk_default=os.path.join(repo or '', SKINS_META_PATH),
                                 hint='（提取产物，由 feat/skins 的 .gitignore 挡住，git 里没有）',
                                 label=SKINS_META_PATH)

    # 1) stem → skinId（提取产物的目录名）
    by_stem = (index.get('byStem') if isinstance(index, dict) else None) or {}
    by_stem = {str(k): str(v) for k, v in by_stem.items()}
    if not by_stem:
        raise SystemExit(f'{index_src.from_text}: 里没有 byStem（stem → skinId）')

    # 2) 提取元数据：skinId → (charId, name, group)，以及 spine 文件名反推的 stem → skinId
    chars = (meta.get('chars') if isinstance(meta, dict) else None) or {}
    if not chars:
        raise SystemExit(f'{meta_src.from_text}: 里没有 chars[charId].skins')
    meta_skins = {}
    meta_stems = {}
    for char_id, rec in chars.items():
        for skin_id, skin in ((rec or {}).get('skins') or {}).items():
            skin = skin or {}
            meta_skins[str(skin_id)] = (str(char_id), (skin.get('name') or '').strip(), (skin.get('group') or '').strip())
            for facing in ('front', 'back'):
                skel = ((skin.get('spine') or {}).get(facing) or {}).get('skel')
                if isinstance(skel, str) and skel.endswith('.skel'):
                    meta_stems.setdefault(skel.rsplit('/', 1)[-1][:-len('.skel')], str(skin_id))

    # 3) 官方 gamedata 生成的皮肤表：skinId → (name, group)，名字的补齐来源
    official = {}
    for char_id, rec in ((names.get('chars') if isinstance(names, dict) else None) or {}).items():
        rows = rec if isinstance(rec, list) else (rec or {}).get('skins', [])
        for row in rows or []:
            skin_id = (row or {}).get('id')
            if skin_id:
                official[str(skin_id)] = (str(char_id), (row.get('name') or '').strip(), (row.get('group') or '').strip())
    if not official:
        raise SystemExit(f'{names_src.from_text}: 里没有 chars[charId][].id / name / group')

    problems = []
    # 4) 逐条核对：index ↔ 提取元数据 ↔ 官方表
    for stem, skin_id in sorted(by_stem.items()):
        if skin_id not in meta_skins:
            problems.append(f'index 里的 stem {stem} → {skin_id}，但提取元数据里没有这套皮肤')
            continue
        if skin_id not in official:
            problems.append(f'{skin_id}（stem {stem}）不在官方 gamedata 生成的皮肤表里')
            continue
        char_id, name, group = meta_skins[skin_id]
        if char_id != skin_id.split('@', 1)[0]:
            problems.append(f'{skin_id} 在提取元数据里挂在 {char_id} 下，与 skinId 前缀不符')
        if meta_stems.get(stem) != skin_id:
            problems.append(f'stem {stem}：index 说 {skin_id}，提取元数据的 .skel 文件名反推是 {meta_stems.get(stem)}')
        off_name, off_group = official[skin_id][1], official[skin_id][2]
        if not off_name or not off_group:
            problems.append(f'{skin_id}：官方表里名字或分组为空')
        if name and name != skin_id and name != off_name:
            problems.append(f'{skin_id}：提取元数据的名字 {name!r} 与官方表 {off_name!r} 不一致')
        if group and group != off_group:
            problems.append(f'{skin_id}：提取元数据的分组 {group!r} 与官方表 {off_group!r} 不一致')
    for stem, skin_id in sorted(meta_stems.items()):
        if stem not in by_stem:
            problems.append(f'提取元数据里的 stem {stem}（{skin_id}）不在 index 里')
    for skin_id in sorted(meta_skins):
        if skin_id not in set(by_stem.values()) and skin_id not in official:
            problems.append(f'提取元数据里的 {skin_id} 在 index 与官方表里都没有')
    if problems:
        say(f'核对不通过：{len(problems)} 条')
        for line in problems[:40]:
            say(f'  {line}')
        if len(problems) > 40:
            say(f'  …还有 {len(problems) - 40} 条')
        return 1

    # 5) 官方 gamedata 快照（可选）：displaySkin 必须与官方表逐条一致
    table_src = None
    table_checked = 0
    table_path = args.official_table or (os.path.join(repo, OFFICIAL_TABLE_PATH) if repo else None)
    if table_path and os.path.isfile(table_path):
        raw = read_bytes(table_path)
        table_src = Source('official-table', os.path.abspath(table_path), raw=raw, label=OFFICIAL_TABLE_PATH)
        char_skins = ((parse_json(raw, table_path) or {}).get('charSkins')) or {}
        for skin_id, (_, name, group) in sorted(official.items()):
            if skin_id not in set(by_stem.values()):
                continue
            ds = (char_skins.get(skin_id) or {}).get('displaySkin') or {}
            got = ((ds.get('skinName') or '').strip(), (ds.get('skinGroupName') or '').strip())
            if got != (name, group):
                problems.append(f'{skin_id}：官方快照 {(got[0], got[1])!r} 与官方表 {(name, group)!r} 不一致')
            else:
                table_checked += 1
        if problems:
            say(f'官方快照核对不通过：{len(problems)} 条')
            for line in problems[:40]:
                say(f'  {line}')
            return 1

    # 6) 逐条写表：名字用提取元数据里的真名，缺的（name == skinId）用官方表补
    skins = []
    for stem, skin_id in sorted(by_stem.items(), key=lambda kv: (kv[1], kv[0])):
        char_id, name, group = meta_skins[skin_id]
        if not name or name == skin_id:
            name, group = official[skin_id][1], official[skin_id][2]
        skins.append({'skinId': skin_id, 'stem': stem, 'charId': char_id, 'name': name, 'group': group})

    from_meta = sum(1 for s in skins if meta_skins[s['skinId']][1] not in ('', s['skinId']))
    doc = {
        'version': 1,
        'note': NOTE,
        'generator': 'tools/local-catalogue.py',
        'source': {
            'repo': 'Stronghold-Protocol',
            'branch': args.ref,
            'files': [src.record() for src in (index_src, meta_src, names_src) if src],
        },
        'counts': {
            'skins': len(skins),
            'characters': len({s['charId'] for s in skins}),
            'named': sum(1 for s in skins if s['name']),
            'grouped': sum(1 for s in skins if s['group']),
            'nameFromExtraction': from_meta,
            'nameFromGeneratedList': len(skins) - from_meta,
        },
        'skins': skins,
    }
    if table_src:
        doc['source']['officialSnapshot'] = dict(table_src.record(), role='官方 gamedata 快照：逐条核对 displaySkin.skinName / skinGroupName')
        doc['source']['officialSnapshotChecked'] = table_checked

    out = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1)
        fh.write('\n')

    say(f'目录表 {out}')
    for src in (index_src, meta_src, names_src, table_src):
        if src:
            say(f'  来源：{src.from_text}（{src.path}，{len(src.raw)} 字节，sha256 {sha256(src.raw)[:16]}…）——{src.role}')
    say(f'  {doc["counts"]["skins"]} 套 / {doc["counts"]["characters"]} 个干员：'
        f'有名字 {doc["counts"]["named"]}、有分组 {doc["counts"]["grouped"]}'
        f'（提取元数据给了 {doc["counts"]["nameFromExtraction"]} 个真名，'
        f'官方生成表补了 {doc["counts"]["nameFromGeneratedList"]} 个）')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
